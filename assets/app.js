  function observeOnce(el, threshold, cb) {
    if (!el) return;
    var obs = new IntersectionObserver(
      function (entries) {
        entries.forEach(function (entry) {
          if (entry.isIntersecting) {
            obs.disconnect();
            cb(el);
          }
        });
      },
      { threshold: threshold }
    );
    obs.observe(el);
  }

      
